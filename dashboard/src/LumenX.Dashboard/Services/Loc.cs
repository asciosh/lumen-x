    public static IReadOnlyDictionary<string, string> ItalianTexts => Italian;

    public static string T(string english, string language, params object[] args)
    {
        var text = language == LanguageState.Italian && Italian.TryGetValue(english, out var italian) ? italian : english;
        return args.Length == 0 ? text : string.Format(CultureInfo.InvariantCulture, text, args);
    }
